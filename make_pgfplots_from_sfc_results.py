#!/usr/bin/env python3
# Generate PGFPlots .tex figure snippets from SFC study results.
#
# Input CSV/TSV must have columns:
#   - load_level in {low, medium, high}
#   - L (int SFC length)
#   - seed (int)
#   - k_value (int)
#   - acceptance_ratio (float 0..1)
#
# Usage:
#   python make_pgfplots_from_sfc_results.py /path/to/results.csv --out figs/
#
# It emits files like:
#   figs/fig_accept_vs_k_L6.tex
#   figs/fig_accept_vs_L_k10.tex
# and a README_OVERLEAF.md with LaTeX usage tips.

import argparse
from pathlib import Path
import pandas as pd
from textwrap import dedent

def make_tex(filename: Path, title: str, xlabel: str, ylabel: str, series_list):
    # Sort x in each series
    series_list = [
        {"label": s["label"], "coords": sorted(s["coords"], key=lambda t: t[0])}
        for s in series_list
    ]
    plots = []
    for s in series_list:
        coords_str = " ".join(f"({x},{y:.4f})" for x, y in s["coords"])
        plots.append(dedent(f"""
            % {s["label"]}
            \\addplot+[thick, mark=*] coordinates {{ {coords_str} }};
            \\addlegendentry{{{s["label"]}}}
        """).strip())
    plots_block = "\n\n".join(plots)

    tex = dedent(f"""
    % Auto-generated by make_pgfplots_from_sfc_results.py
    % File: {filename.name}
    \\begin{{tikzpicture}}
      \\begin{{axis}}[
        width=\\linewidth,
        height=0.55\\linewidth,
        title={{{title}}},
        xlabel={{{{ {xlabel} }}}},
        ylabel={{{{ {ylabel} }}}},
        legend pos=south east,
        grid=both,
        ymin=0, ymax=1.05,
        yminorticks=true,
        ymajorgrids=true,
        xmajorgrids=true,
        tick align=outside,
        tick style={{very thin}},
        legend cell align=left
      ]
      {plots_block}
      \\end{{axis}}
    \\end{{tikzpicture}}
    """).strip()

    filename.write_text(tex)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("csv", help="results CSV/TSV file")
    ap.add_argument("--out", default="figs", help="output directory for .tex files")
    ap.add_argument("--kset", default="1,3,5,10,15", help="comma list of k values to include for L-plots")
    args = ap.parse_args()

    df = pd.read_csv(args.csv, sep=None, engine="python")
    required = {"load_level", "L", "seed", "k_value", "acceptance_ratio"}
    missing = required - set(df.columns)
    if missing:
        raise SystemExit(f"Missing columns: {missing}")

    load_order = ["low", "medium", "high"]
    df["load_level"] = pd.Categorical(df["load_level"], categories=load_order, ordered=True)

    outdir = Path(args.out)
    outdir.mkdir(parents=True, exist_ok=True)

    # 1) Acceptance vs k for each fixed L
    Ls = sorted(df["L"].unique().tolist())
    for Lval in Ls:
        dL = df[df["L"] == Lval]
        series = []
        for load in load_order:
            d = dL[dL["load_level"] == load]
            if d.empty:
                continue
            agg = d.groupby("k_value")["acceptance_ratio"].mean().reset_index()
            series.append({
                "label": load.capitalize(),
                "coords": list(zip(agg["k_value"].tolist(), agg["acceptance_ratio"].tolist()))
            })
        fname = outdir / f"fig_accept_vs_k_L{Lval}.tex"
        make_tex(
            fname,
            title=f"Acceptance vs $k$ at fixed $L={Lval}$",
            xlabel="$k$ (k-shortest paths)",
            ylabel="Acceptance ratio",
            series_list=series
        )

    # 2) Acceptance vs L for selected fixed k values
    ks = sorted(df["k_value"].unique().tolist())
    kset = [int(s) for s in args.kset.split(",") if s.strip()]
    present_k = [k for k in kset if k in ks]
    for kval in present_k:
        dK = df[df["k_value"] == kval]
        series = []
        for load in load_order:
            d = dK[dK["load_level"] == load]
            if d.empty:
                continue
            agg = d.groupby("L")["acceptance_ratio"].mean().reset_index()
            series.append({
                "label": load.capitalize(),
                "coords": list(zip(agg["L"].tolist(), agg["acceptance_ratio"].tolist()))
            })
        fname = outdir / f"fig_accept_vs_L_k{kval}.tex"
        make_tex(
            fname,
            title=f"Acceptance vs $L$ at fixed $k={kval}$",
            xlabel="$L$ (SFC length)",
            ylabel="Acceptance ratio",
            series_list=series
        )

    readme = dedent(f"""
    # Overleaf usage

    Add to preamble:
      \\usepackage{{pgfplots}}
      \\pgfplotsset{{compat=1.18}}
      \\usepackage{{tikz}}

    Upload all .tex from `{outdir}` to an Overleaf folder `figs/`,
    then include them with:
      \\input{{figs/fig_accept_vs_k_L6.tex}}
    """).strip()
    (outdir / "README_OVERLEAF.md").write_text(readme)

if __name__ == "__main__":
    main()
